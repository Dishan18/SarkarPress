function appendToFile(filePath, newObj) {
  let content = fs.readFileSync(filePath, 'utf8');
  let newProps = Object.entries(newObj).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
  content = content.replace(/};/, `${newProps}\n};`);
  fs.writeFileSync(filePath, content);
}

